// Writes dsp/axe_targets.h: the Tone Match preset targets (host/target_models.h)
// as the profiles Tone Match's Learner measures.
//   ./make_targets > dsp/axe_targets.h
#include "target_models.h"
#include <cstdio>

int main() {
    std::printf("// Tone Match preset targets. Generated by host/make_targets.cpp from the\n"
                "// models in host/target_models.h: don't edit by hand (engine_test checks it).\n"
                "// Each row: dB per band (250 Hz ... 10 kHz) re the mean of the 250 Hz-1 kHz\n"
                "// bands, as Learner measures it.\n"
                "#pragma once\n\nnamespace axe {\n\n");
    std::printf("constexpr int kNumTargetPresets = %d;\n", targets::kNum);
    std::printf("constexpr const char* kTargetPresetNames[kNumTargetPresets] = {");
    for (int i = 0; i < targets::kNum; i++) std::printf("%s\"%s\"", i ? ", " : "", targets::kModels[i].name);
    std::printf("};\nconstexpr bool kTargetPresetBass[kNumTargetPresets] = {");
    for (int i = 0; i < targets::kNum; i++) std::printf("%s%s", i ? ", " : "", targets::kModels[i].bass ? "true" : "false");
    std::printf("};\nconstexpr float kTargetPresets[kNumTargetPresets][8] = {\n");
    for (int i = 0; i < targets::kNum; i++) {
        float p[8];
        targets::profile(targets::render(targets::kModels[i]), strings::kSR, p);
        std::printf("    {");
        for (int b = 0; b < 8; b++) std::printf("%s%.2ff", b ? ", " : "", p[b]);
        std::printf("},   // %s\n", targets::kModels[i].name);
    }
    std::printf("};\n\n}  // namespace axe\n");
    return 0;
}
